"""VOD and Live clipping workers wrapping existing open-short pipelines."""
from __future__ import annotations

import asyncio
import glob
import json
import logging
import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

from .config import AutopilotConfig
from .exceptions import PermanentError, RetryableError
from .models import JobStatus, ProcessingJob
from .quality import ClipQualityValidator
from .queue import PersistentQueue
from .storage import LocalMediaStorage

logger = logging.getLogger("autopilot.workers")


class VODWorker:
    """Processes queued VOD jobs using existing main.py clipping pipeline."""

    def __init__(
        self,
        config: AutopilotConfig,
        queue: PersistentQueue,
        quality: ClipQualityValidator,
        storage: LocalMediaStorage,
    ):
        self.config = config
        self.queue = queue
        self.quality = quality
        self.storage = storage

    def process_job(self, job: ProcessingJob) -> List[str]:
        """Run main.py for a claimed VOD job, validate clips, and register approved MP4s."""
        source_row = self._get_source_row(job.source_pk)
        if not source_row:
            raise PermanentError(f"Source row missing for job {job.id}")

        job_temp_dir = self.config.temp_dir / "renders" / job.id
        job_temp_dir.mkdir(parents=True, exist_ok=True)

        self._invoke_main_pipeline(source_row["url"], job_temp_dir)

        clips = self._collect_generated_clips(job_temp_dir)
        if not clips:
            raise PermanentError(f"No clips generated by main.py for job {job.id}")

        self.queue.transition_job(job.id, JobStatus.CLIPS_GENERATED)

        approved_clip_ids: List[str] = []
        for clip_meta in clips:
            if len(approved_clip_ids) >= self.config.max_clips_per_source:
                break

            start_t = float(clip_meta.get("start_time") or clip_meta.get("start") or 0.0)
            end_t = float(clip_meta.get("end_time") or clip_meta.get("end") or 0.0)
            score = float(clip_meta.get("score") or 0.0)
            mp4_path = Path(clip_meta["file_path"])

            qres = self.quality.validate(mp4_path)
            if not qres.passed:
                logger.info("Clip rejected by quality gate (%s): %s", mp4_path.name, qres.reason)
                continue

            if end_t <= start_t:
                end_t = start_t + qres.duration_sec

            moment_id = self.queue.record_moment_if_unique(
                job_id=job.id,
                platform=job.platform,
                source_id=job.source_id,
                start_time=start_t,
                end_time=end_t,
                moment_score=score,
                reason=str(clip_meta.get("reason") or ""),
            )
            if moment_id is None:
                logger.info("Skipping duplicate overlapping moment for %s", job.source_id)
                continue

            clip_id = self.storage.register_approved_clip(
                job_id=job.id,
                moment_id=moment_id,
                src_path=mp4_path,
                duration_sec=qres.duration_sec,
                width=qres.width,
                height=qres.height,
                file_size_bytes=qres.file_size_bytes,
            )
            approved_clip_ids.append(clip_id)

        if not approved_clip_ids:
            raise PermanentError(f"All generated clips failed quality/dedup for job {job.id}")

        self.queue.transition_job(job.id, JobStatus.QUALITY_APPROVED)
        return approved_clip_ids

    def _invoke_main_pipeline(self, url: str, output_dir: Path) -> None:
        main_py = self.config.base_dir / "main.py"
        cmd = [
            sys.executable,
            str(main_py),
            "-u",
            url,
            "-o",
            str(output_dir),
            "--format",
            "vertical",
        ]
        env = os.environ.copy()
        env["CONTENT_PROFILE"] = "gaming"
        env["CLIPPING_PROFILE"] = "gaming"
        env["TEMPLATE_ID"] = "streamer_stacked_top"
        env["STREAMER_CAM_POSITION"] = "top"
        env["MAX_CLIP_DURATION"] = str(self.config.clip_max_duration)
        env["MIN_CLIP_DURATION"] = str(self.config.clip_min_duration)

        try:
            res = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=1800)
        except subprocess.TimeoutExpired as e:
            raise RetryableError(f"main.py timed out for {url}") from e

        if res.returncode != 0:
            err = (res.stderr or res.stdout or "")[-400:]
            raise RetryableError(f"main.py exited {res.returncode}: {err}")

    def _collect_generated_clips(self, output_dir: Path) -> List[Dict[str, Any]]:
        meta_files = sorted(glob.glob(str(output_dir / "*_metadata.json")))
        clips: List[Dict[str, Any]] = []
        if meta_files:
            data = json.loads(Path(meta_files[0]).read_text(encoding="utf-8"))
            shorts = data.get("shorts") or []
            mp4s = sorted(output_dir.glob("clip_*.mp4"))
            for idx, s in enumerate(shorts):
                fp = s.get("file_path") or s.get("output_path")
                if not fp and idx < len(mp4s):
                    fp = str(mp4s[idx])
                if fp and Path(fp).exists():
                    clips.append({**s, "file_path": fp})
            if clips:
                return clips

        for mp4 in sorted(output_dir.glob("*.mp4")):
            clips.append({"file_path": str(mp4), "start_time": 0.0, "end_time": 0.0})
        return clips

    def _get_source_row(self, source_pk: int):
        with self.queue.db.transaction() as conn:
            return conn.execute("SELECT * FROM discovered_sources WHERE id = ?", (source_pk,)).fetchone()


class LiveWorker:
    """Monitors live streams via LiveHypePipeline with chat-first detection and cooldown."""

    def __init__(
        self,
        config: AutopilotConfig,
        queue: PersistentQueue,
        quality: ClipQualityValidator,
        storage: LocalMediaStorage,
    ):
        self.config = config
        self.queue = queue
        self.quality = quality
        self.storage = storage

    def process_job(self, job: ProcessingJob) -> List[str]:
        """Run bounded-window live monitoring using LiveHypePipeline."""
        with self.queue.db.transaction() as conn:
            src = conn.execute("SELECT * FROM discovered_sources WHERE id = ?", (job.source_pk,)).fetchone()
        if not src:
            raise PermanentError(f"Source row missing for live job {job.id}")

        from gaming_intelligence.live.pipeline import LiveHypePipeline

        buf_dir = self.config.temp_dir / "live_buffer" / job.id
        out_dir = self.config.temp_dir / "live_renders" / job.id
        pipe = LiveHypePipeline(
            buffer_dir=str(buf_dir),
            output_dir=str(out_dir),
            pre_roll_sec=max(20.0, float(self.config.clip_min_duration) - 10.0),
            post_roll_sec=10.0,
        )
        pipe.detector.cooldown_sec = float(self.config.live_clip_cooldown_seconds)

        async def _run_bounded() -> None:
            coro = (
                pipe.start_twitch(src["channel_name"].lower(), stream_url=src["url"])
                if job.platform == "twitch"
                else pipe.start_youtube(src["source_id"], api_key=self.config.youtube_api_key)
            )
            try:
                await asyncio.wait_for(coro, timeout=float(self.config.live_monitor_window_minutes * 60))
            except asyncio.TimeoutError:
                pass
            finally:
                pipe.scheduler.close()

        try:
            loop = asyncio.get_event_loop()
            if loop.is_running():
                import concurrent.futures
                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
                    pool.submit(asyncio.run, _run_bounded()).result()
            else:
                loop.run_until_complete(_run_bounded())
        except RuntimeError:
            asyncio.run(_run_bounded())

        if not pipe.completed_jobs:
            raise RetryableError(f"No live hype clips captured during window for {job.source_id}")

        self.queue.transition_job(job.id, JobStatus.CLIPS_GENERATED)
        approved_clip_ids: List[str] = []

        for cjob in pipe.completed_jobs:
            if len(approved_clip_ids) >= self.config.max_clips_per_source:
                break
            if not cjob.final_path or not Path(cjob.final_path).exists():
                continue
            qres = self.quality.validate(cjob.final_path)
            if not qres.passed:
                continue
            start_t = float(getattr(cjob.event, "detected_at", 0.0) or 0.0)
            end_t = start_t + qres.duration_sec
            moment_id = self.queue.record_moment_if_unique(
                job_id=job.id,
                platform=job.platform,
                source_id=job.source_id,
                start_time=start_t,
                end_time=end_t,
                moment_score=float(getattr(cjob.event, "z_score", 0.0) or 0.0),
                reason="live_chat_hype",
            )
            if moment_id is None:
                continue
            clip_id = self.storage.register_approved_clip(
                job_id=job.id,
                moment_id=moment_id,
                src_path=Path(cjob.final_path),
                duration_sec=qres.duration_sec,
                width=qres.width,
                height=qres.height,
                file_size_bytes=qres.file_size_bytes,
            )
            approved_clip_ids.append(clip_id)

        if not approved_clip_ids:
            raise PermanentError(f"No valid live clips approved for job {job.id}")

        self.queue.transition_job(job.id, JobStatus.QUALITY_APPROVED)
        return approved_clip_ids
